import { describe, expect, it } from 'vitest';
import preflightOkOrg from './__contract__/preflight_ok_org.json';
import remediationCodes from './__contract__/remediation_codes.json';
import {
  normalizePreflight,
  PreflightWireResponseSchema,
  REMEDIATION_CODES,
} from './api';

describe('API-key wire contract (fixtures generated by the Rust serializer)', () => {
  // CTR-01: one remediation vocabulary on both sides.
  it('REMEDIATION_CODES equals the Rust RemediationCode::ALL', () => {
    expect([...REMEDIATION_CODES]).toEqual(remediationCodes);
    expect(new Set(REMEDIATION_CODES).size).toBe(16);
  });

  // PF-01: the Rust preflight snapshot passes the zod schema.
  it('PreflightWireResponseSchema parses the Rust preflight fixture', () => {
    const wire = PreflightWireResponseSchema.parse(preflightOkOrg);
    expect(normalizePreflight(wire)).toEqual({
      verdict: 'ok',
      key_class: 'org_scoped',
      inference: 'ok',
      workspace: {
        mode: 'selected',
        id: 'wrkspc_01Prod',
        name: 'Production',
      },
      workspaces: [
        { id: 'wrkspc_01Prod', name: 'Production' },
        { id: 'wrkspc_02Stage', name: 'Staging' },
      ],
      workspace_list: 'ok',
      usage_report: 'ok',
      key_type: 'service_account',
      remediation: [],
    });
  });

  it('PreflightWireResponseSchema rejects an unknown remediation code', () => {
    const drifted = {
      ...preflightOkOrg,
      remediation: [{ code: 'restricted_key' }],
    };
    expect(PreflightWireResponseSchema.safeParse(drifted).success).toBe(false);
  });
});
